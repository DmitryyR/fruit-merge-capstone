import {chromium} from '@playwright/test';
import {writeFileSync} from 'node:fs';
const url=process.env.FRUIT_PUBLIC_URL??'https://dmitryyr.github.io/fruit-merge-capstone/';
const browser=await chromium.launch();
const page=await browser.newPage({viewport:{width:1440,height:900}});
const failures=[],errors=[],assets=new Map();
page.on('pageerror',e=>errors.push(e.message));
page.on('response',r=>{if(r.url().includes('/assets/')){assets.set(r.url(),r.status());if(r.status()>=400)failures.push({url:r.url(),status:r.status()});}});
page.on('requestfailed',r=>failures.push({url:r.url(),error:r.failure()?.errorText}));
const response=await page.goto(url,{waitUntil:'networkidle'});
if(response.status()!==200)throw new Error(`Site returned ${response.status()}`);
await page.getByRole('button',{name:'Пауза',exact:true}).waitFor();
if(await page.evaluate(()=>('__FRUIT_MERGE_TEST__' in window)))throw new Error('Test API exposed');
const box=await page.locator('canvas').boundingBox();
for(let i=0;i<10;i++){await page.mouse.click(box.x+box.width*(.15+(i%5)*.17),box.y+box.height*.3);await page.waitForTimeout(400);}
await page.waitForTimeout(1300);
await page.screenshot({path:'docs/evidence/screenshots/public-desktop.png'});
await page.getByRole('button',{name:'Пауза',exact:true}).click();
await page.getByRole('button',{name:'Продовжити',exact:true}).waitFor();
await page.getByRole('button',{name:'Нова гра',exact:true}).click();
if(await page.locator('#score').textContent()!=='0')throw new Error('Restart failed');
await page.setViewportSize({width:390,height:844});
if(!await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth))throw new Error('Horizontal overflow');
await page.screenshot({path:'docs/evidence/screenshots/public-mobile.png'});
await page.goto(`${url}?view=sizes`,{waitUntil:'networkidle'});
await page.waitForSelector('[data-ready="true"]');
const cards=await page.locator('.size-grid canvas').count();if(cards!==30)throw new Error(`Expected 30, got ${cards}`);
const fruitAssets=[...assets].filter(([path])=>/fruit-\d\d\.webp/.test(path));if(fruitAssets.length!==30)throw new Error('Missing fruit assets');
const orchard=[...assets].filter(([path])=>path.includes('/orchard/background.webp'));if(orchard.length!==1)throw new Error('Missing background');
if(failures.length||errors.length)throw new Error(JSON.stringify({failures,errors}));
writeFileSync('docs/evidence/runs/public-deployment.json',JSON.stringify({url,checkedAt:new Date().toISOString(),httpStatus:response.status(),desktop:'1440x900',mobile:'390x844',productionApiAbsent:true,dropGestures:10,pauseAndRestart:true,diagnosticCards:cards,fruitAssets:fruitAssets.length,backgroundLoaded:true,failures,errors,assets:[...assets]},null,2));
await browser.close();console.log('Public deployment verified: HTTPS 200; 30 fruits and background; drop/pause/restart; desktop/mobile; diagnostic; no errors/test API.');
